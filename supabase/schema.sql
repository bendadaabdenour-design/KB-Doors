-- KBDOOR: tables for orders and contact/quote requests.
-- Run this script in Supabase Dashboard > SQL Editor.

create table if not exists public.commandes (
  id text primary key,
  date text not null,
  client text not null,
  phone text not null,
  wilaya text not null,
  address text not null,
  payment text not null,
  total text not null,
  items jsonb not null default '[]'::jsonb
);

create table if not exists public.commande_articles (
  id bigint generated by default as identity primary key,
  commande_id text not null references public.commandes(id) on delete cascade,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  color text,
  dimension text,
  opening text,
  handle text,
  frame text,
  hex text,
  created_at timestamptz not null default now()
);

create index if not exists commande_articles_commande_id_idx
  on public.commande_articles (commande_id);

create table if not exists public.demandes_contact (
  id bigint generated by default as identity primary key,
  date text not null,
  name text not null,
  phone text not null,
  wilaya text not null,
  message text not null
);

alter table public.commandes enable row level security;
alter table public.commande_articles enable row level security;
alter table public.demandes_contact enable row level security;

-- Anonymous clients may submit orders and contact requests, but cannot read them.
grant usage on schema public to anon;
grant insert on table public.commandes to anon;
grant insert on table public.demandes_contact to anon;
grant usage, select on sequence public.demandes_contact_id_seq to anon;

drop policy if exists "Allow anonymous order submissions" on public.commandes;
create policy "Allow anonymous order submissions"
  on public.commandes for insert to anon with check (true);

drop policy if exists "Allow anonymous contact submissions" on public.demandes_contact;
create policy "Allow anonymous contact submissions"
  on public.demandes_contact for insert to anon with check (true);

-- Atomic RPC: create the order and its individual article rows in one transaction.
create or replace function public.enregistrer_commande(p_order jsonb)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_id text;
begin
  v_order_id := p_order ->> 'id';

  if v_order_id is null or v_order_id = '' then
    raise exception 'L’identifiant de commande est obligatoire';
  end if;
  if jsonb_typeof(coalesce(p_order -> 'items', '[]'::jsonb)) <> 'array' then
    raise exception 'items doit être un tableau JSON';
  end if;

  insert into public.commandes (
    id, date, client, phone, wilaya, address, payment, total, items
  ) values (
    v_order_id,
    coalesce(p_order ->> 'date', to_char(now(), 'DD/MM/YYYY HH24:MI:SS')),
    coalesce(p_order ->> 'client', ''),
    coalesce(p_order ->> 'phone', ''),
    coalesce(p_order ->> 'wilaya', ''),
    coalesce(p_order ->> 'address', ''),
    coalesce(p_order ->> 'payment', ''),
    coalesce(p_order ->> 'total', '0'),
    coalesce(p_order -> 'items', '[]'::jsonb)
  );

  insert into public.commande_articles (
    commande_id, product_name, quantity, unit_price,
    color, dimension, opening, handle, frame, hex
  )
  select
    v_order_id,
    coalesce(item ->> 'productName', 'Article'),
    coalesce(nullif(item ->> 'qty', '')::integer, 1),
    coalesce(nullif(item ->> 'unitPrice', '')::numeric, 0),
    item ->> 'color',
    item ->> 'dimension',
    item ->> 'opening',
    item ->> 'handle',
    item ->> 'frame',
    item ->> 'hex'
  from jsonb_array_elements(coalesce(p_order -> 'items', '[]'::jsonb)) as item;

  return v_order_id;
end;
$$;

revoke all on function public.enregistrer_commande(jsonb) from public;
revoke all on function public.enregistrer_commande(jsonb) from anon, authenticated;
grant execute on function public.enregistrer_commande(jsonb) to anon;
