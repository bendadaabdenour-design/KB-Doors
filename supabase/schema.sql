-- KBDOOR: tables for orders and contact/quote requests.
-- Run this script in Supabase Dashboard > SQL Editor.

create table if not exists public.commandes (
  id text primary key,
  date text not null,
  client text not null,
  phone text not null,
  wilaya text not null,
  address text not null,
  payment text not null,
  total text not null,
  items jsonb not null default '[]'::jsonb
);

create table if not exists public.demandes_contact (
  id bigint generated by default as identity primary key,
  date text not null,
  name text not null,
  phone text not null,
  wilaya text not null,
  message text not null
);

alter table public.commandes enable row level security;
alter table public.demandes_contact enable row level security;

-- The storefront is anonymous: allow inserts only. No public read/update/delete access.
grant insert on table public.commandes to anon;
grant insert on table public.demandes_contact to anon;
grant usage, select on sequence public.demandes_contact_id_seq to anon;

drop policy if exists "Allow anonymous order submissions" on public.commandes;
create policy "Allow anonymous order submissions"
  on public.commandes for insert to anon with check (true);

drop policy if exists "Allow anonymous contact submissions" on public.demandes_contact;
create policy "Allow anonymous contact submissions"
  on public.demandes_contact for insert to anon with check (true);
